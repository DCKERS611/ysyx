// RV32为小端；低字节索引通过sb/lw完成，表基址的低8位由对齐保证为0。
static inline unsigned uart_status_bit(const unsigned char *table, unsigned char status) {
    volatile uintptr_t address = (uintptr_t)table;
    ((volatile unsigned char *)&address)[0] = status;
    return *(const unsigned char *)address;
}
