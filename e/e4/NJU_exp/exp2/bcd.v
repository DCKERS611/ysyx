    input [3:0]     bcd,
	input			en,
    output [7:0]    seg
);
    wire [7:0] bcd_out;
    MuxKey #(16,4,8) u_bcd (
    bcd_out, bcd , {
    4'd0,  8'b1111_1100,
    4'd1,  8'b0110_0000,
    4'd2,  8'b1101_1010,
	4'd3,  8'b1111_0010,
	4'd4,  8'b0110_0110,
	4'd5,  8'b1011_0110,
	4'd6,  8'b1011_1110,
	4'd7,  8'b1110_0000,
	4'd8,  8'b1111_1110,
	4'd9,  8'b1111_0110,
	4'd10, 8'b0000_0000,
	4'd11, 8'b0000_0000,
	4'd12, 8'b0000_0000,
	4'd13, 8'b0000_0000,
	4'd14, 8'b0000_0000,
	4'd15, 8'b0000_0000
    });
	assign seg = en ? ~bcd_out : 8'b0000_0000;
endmodule
